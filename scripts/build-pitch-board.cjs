const { build } = require('esbuild');
const fs = require('node:fs/promises');
const path = require('node:path');

async function main() {
  const root = path.join(__dirname, '..');
  const license = await fs.readFile(path.join(root, 'node_modules/three/LICENSE'), 'utf8');
  const { outputFiles } = await build({
    absWorkingDir: root,
    entryPoints: ['src/pitch-board.js'],
    bundle: true,
    minify: true,
    supported: { 'template-literal': false },
    target: ['safari16.4', 'chrome100'],
    format: 'iife',
    globalName: 'PitchBoard',
    loader: { '.css': 'text' },
    banner: { js: `/* Generated by npm run build:board.\nThree.js license\n${license.trim()}\n*/` },
    write: false,
  });
  const script = outputFiles[0].text;
  await fs.writeFile(path.join(root, 'assets/pitch-board-3d.js'), script);

  // The native app injects the same renderer into its bundled WebView document.
  if (process.argv[2]) {
    const nativeRoot = path.resolve(process.argv[2]);
    const { expo } = JSON.parse(await fs.readFile(path.join(nativeRoot, 'app.json'), 'utf8'));
    if (expo?.ios?.bundleIdentifier !== 'com.kokokikaku.pitch') {
      throw new Error('Specify the root of the Pitch Dictionary iOS project.');
    }
    await fs.writeFile(path.join(nativeRoot, 'assets/pitch-board-3d.json'), JSON.stringify({ script }) + '\n');
  }
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
