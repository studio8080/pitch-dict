export function sampleTrack(track, phase, smooth = false, cuts = []) {
  const end = track.findIndex(([time]) => time > phase);
  if (end === -1) return track.at(-1).slice(1);
  if (end === 0) return track[0].slice(1);
  const [start, x, y, height = 0] = track[end - 1];
  const [finish, nextX, nextY, nextHeight = 0] = track[end];
  if (cuts.includes(finish)) return [x, y, height];
  const t = (phase - start) / (finish - start);
  const weight = smooth ? t * t * (3 - 2 * t) : t;
  return [x + (nextX - x) * weight, y + (nextY - y) * weight, height + (nextHeight - height) * weight];
}

export function phaseAt(play, milliseconds, reduced) {
  const duration = play.seconds * 1000;
  return reduced ? play.still : (milliseconds % duration) / duration;
}

export function kickAt(play, key, phase) {
  const cue = play.kicks?.find(([time, player]) => player === key && Math.abs(phase - time) < .07);
  if (!cue) return null;
  const [time] = cue;
  const [x, y] = sampleTrack(play.ball, time);
  const [nextX, nextY] = sampleTrack(play.ball, time + .04);
  return { heading: Math.atan2(nextX - x, nextY - y), strike: Math.max(0, 1 - Math.abs(phase - time) / .052) };
}
